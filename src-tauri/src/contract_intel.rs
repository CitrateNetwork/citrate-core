fn opt_str(v: &Value, k: &str) -> Option<String> {
    v.get(k)
        .and_then(Value::as_str)
        .map(|s| s.to_ascii_lowercase())
}

fn quantity_dec(v: &Value, k: &str) -> Result<Option<String>, String> {
    match v.get(k).and_then(Value::as_str) {
        None => Ok(None),
        Some(s) => {
            let h = s
                .strip_prefix("0x")
                .ok_or_else(|| format!("the node's {k} is not a 0x quantity"))?;
            let n = u128::from_str_radix(if h.is_empty() { "0" } else { h }, 16)
                .map_err(|_| format!("the node's {k} is not a quantity"))?;
            Ok(Some(n.to_string()))
        }
    }
}

/// `chain_tx_fetch(hash)`: the transaction and its receipt, shaped for decoding.
pub fn fetch_tx<T: RpcTransport>(rpc: &RpcClient<T>, hash: &str) -> Result<TxFetch, String> {
    let hash = hex_key(hash, 32)
        .map_err(|_| "a transaction hash is 0x followed by 64 hex digits".to_string())?;
    let tx = rpc_raw(rpc, "eth_getTransactionByHash", json!([hash]))?;
    let mut out = TxFetch {
        hash: hash.clone(),
        found: false,
        from: None,
        to: None,
        value_wei: None,
        input: None,
        input_truncated: false,
        nonce: None,
        block_number: None,
        status: "pending".into(),
        gas_used: None,
        contract_address: None,
        logs: Vec::new(),
        logs_truncated: false,
        names: BTreeMap::new(),
    };
    if tx.is_null() {
        return Ok(out);
    }
    out.found = true;
    out.from = opt_str(&tx, "from");
    out.to = opt_str(&tx, "to");
    out.value_wei = quantity_dec(&tx, "value")?;
    out.nonce = quantity_dec(&tx, "nonce")?;
    out.block_number = quantity_dec(&tx, "blockNumber")?;
    if let Some(input) = opt_str(&tx, "input").or_else(|| opt_str(&tx, "data")) {
        let max = 2 + MAX_TX_INPUT_BYTES * 2;
        out.input_truncated = input.len() > max;
        out.input = Some(input.chars().take(max).collect());
    }
    let receipt = rpc_raw(rpc, "eth_getTransactionReceipt", json!([hash]))?;
    if !receipt.is_null() {
        out.status = match receipt.get("status").and_then(Value::as_str) {
            Some("0x1") => "success".into(),
            Some("0x0") => "reverted".into(),
            _ => return Err("the node's receipt has no status".into()),
        };
        out.gas_used = quantity_dec(&receipt, "gasUsed")?;
        out.contract_address = opt_str(&receipt, "contractAddress");
        let logs = receipt
            .get("logs")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        out.logs_truncated = logs.len() > MAX_TX_LOGS;
        for l in logs.iter().take(MAX_TX_LOGS) {
            let address = opt_str(l, "address").ok_or("a receipt log has no address")?;
            let topics = l
                .get("topics")
                .and_then(Value::as_array)
                .map(|a| {
                    a.iter()
                        .filter_map(Value::as_str)
                        .map(str::to_ascii_lowercase)
                        .collect()
                })
                .unwrap_or_default();
            out.logs.push(TxLog {
                address,
                topics,
                data: opt_str(l, "data").unwrap_or_else(|| "0x".into()),
                log_index: opt_str(l, "logIndex"),
            });
        }
    }
    let entries = book_entries()?;
    let mut addrs: BTreeSet<String> = BTreeSet::new();
    addrs.extend(out.from.clone());
    addrs.extend(out.to.clone());
    addrs.extend(out.contract_address.clone());
    addrs.extend(out.logs.iter().map(|l| l.address.clone()));
    for a in addrs {
        let n = names_for(entries, &a);
        if !n.is_empty() {
            out.names.insert(a, n);
        }
    }
    Ok(out)
}

