fn hex_bytes(v: &Value, what: &str) -> Result<Vec<u8>, String> {
    let s = v
        .as_str()
        .and_then(|s| s.strip_prefix("0x"))
        .ok_or_else(|| format!("the node's {what} result is not 0x hex"))?;
    hex::decode(s).map_err(|_| format!("the node's {what} result is not valid hex"))
}

/// The runtime code at `address` (empty for an account without code).
pub fn get_code_bytes<T: RpcTransport>(
    rpc: &RpcClient<T>,
    address: &str,
) -> Result<Vec<u8>, String> {
    let v = rpc_raw(rpc, "eth_getCode", json!([address, "latest"]))?;
    hex_bytes(&v, "eth_getCode")
}

/// An address held in the low 20 bytes of a 32-byte word whose high 12 bytes are zero, unless
/// it is the zero address.
fn word_address(w: &[u8]) -> Option<String> {
    if w.len() != 32 || w[..12].iter().any(|&b| b != 0) || w[12..].iter().all(|&b| b == 0) {
        return None;
    }
    Some(format!("0x{}", hex::encode(&w[12..])))
}

fn storage_address<T: RpcTransport>(
    rpc: &RpcClient<T>,
    address: &str,
    slot: &str,
) -> Result<Option<String>, String> {
    let v = rpc_raw(rpc, "eth_getStorageAt", json!([address, slot, "latest"]))?;
    let b = hex_bytes(&v, "eth_getStorageAt")?;
    let mut w = vec![0u8; 32usize.saturating_sub(b.len())];
    w.extend_from_slice(&b);
    Ok(word_address(&w))
}

/// The EIP-1167 implementation encoded in minimal-proxy runtime code.
pub fn eip1167_target(code: &[u8]) -> Option<String> {
    if code.len() != 45 || code[..10] != EIP1167_PREFIX || code[30..] != EIP1167_SUFFIX {
        return None;
    }
    Some(format!("0x{}", hex::encode(&code[10..30])))
}

/// Detect a proxy at `address` with runtime `code`. Storage that cannot be read is an error, not
/// "not a proxy".
pub fn detect_proxy<T: RpcTransport>(
    rpc: &RpcClient<T>,
    entries: &[BookEntry],
    address: &str,
    code: &[u8],
) -> Result<Option<ProxyInfo>, String> {
    if code.is_empty() {
        return Ok(None);
    }
    let found = if let Some(t) = eip1167_target(code) {
        Some(("eip-1167", t, None))
    } else if let Some(t) = storage_address(rpc, address, EIP1967_IMPLEMENTATION_SLOT)? {
        Some(("eip-1967", t, None))
    } else if let Some(beacon) = storage_address(rpc, address, EIP1967_BEACON_SLOT)? {
        let ret = rpc
            .eth_call(call_to(&beacon, &selector("implementation()")))
            .map_err(|e| format!("the beacon's implementation() could not be read: {e}"))?;
        let t = word_address(ret.get(..32).unwrap_or_default())
            .ok_or_else(|| "the beacon's implementation() is not an address".to_string())?;
        Some(("eip-1967-beacon", t, Some(beacon)))
    } else {
        storage_address(rpc, address, EIP1822_PROXIABLE_SLOT)?.map(|t| ("eip-1822", t, None))
    };
    let Some((kind, implementation, beacon)) = found else {
        return Ok(None);
    };
    let implementation_code_size = get_code_bytes(rpc, &implementation).ok().map(|c| c.len());
    Ok(Some(ProxyInfo {
        kind: kind.to_string(),
        implementation_book_names: names_for(entries, &implementation),
        implementation,
        beacon,
        implementation_code_size,
    }))
}

/// The explorer's verification status for `address`, or `unavailable` with the reason.
pub fn verified_status(scan: &dyn ScanHttp, base: &str, address: &str) -> VerifiedStatus {
    match crate::verified_source::lookup(scan, base, address) {
        Ok(v) => VerifiedStatus {
            status: v.status,
            contract_name: v.contract_name,
            note: v.note,
        },
        Err(e) => VerifiedStatus {
            status: "unavailable".into(),
            contract_name: None,
            note: format!("CitrateScan's verification status could not be read ({e}); unknown, not unverified."),
        },
    }
}

/// `get_code(address)`.
pub fn get_code<T: RpcTransport>(
    rpc: &RpcClient<T>,
    scan: &dyn ScanHttp,
    explorer_base: &str,
    address: &str,
) -> Result<CodeInfo, String> {
    let address = normalize_address(address)?;
    let entries = book_entries()?;
    let code = get_code_bytes(rpc, &address)?;
    let is_contract = !code.is_empty();
    let proxy = detect_proxy(rpc, entries, &address, &code)?;
    let verified = if is_contract {
        verified_status(scan, explorer_base, &address)
    } else {
        VerifiedStatus {
            status: "unverified".into(),
            contract_name: None,
            note: "There is no contract code at this address (an externally owned account, or nothing deployed yet).".into(),
        }
    };
    let note = if is_contract {
        format!("{} bytes of runtime code on chain 40204.", code.len())
    } else {
        "No code at this address on chain 40204.".to_string()
    };
    Ok(CodeInfo {
        book_names: names_for(entries, &address),
        code_hash: is_contract.then(|| format!("0x{}", hex::encode(Keccak256::digest(&code)))),
        code_size: code.len(),
        is_contract,
        proxy,
        verified,
        address,
        note,
    })
}

