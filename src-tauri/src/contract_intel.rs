/// What `identify_contract` returns.
#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Identity {
    pub address: String,
    pub book_names: Vec<String>,
    pub is_contract: bool,
    pub code_size: usize,
    pub code_hash: Option<String>,
    pub proxy: Option<ProxyInfo>,
    pub verified: VerifiedStatus,
    /// verified | partial-match | book | none
    pub abi_source: String,
    /// The bundled ABI's contract, when `abi_source` is book.
    pub abi_contract: Option<String>,
    /// yes | no | unknown
    pub erc165: String,
    /// interface name -> yes | no (only when ERC-165 answered yes).
    pub interfaces: BTreeMap<String, String>,
    pub erc20: Erc20Guess,
    pub known_selectors: Vec<CodeSelector>,
    /// PUSH4 constants in the code matching no known signature (not all are selectors).
    pub unknown_push4_count: usize,
    pub note: String,
}

/// `supportsInterface(id)`: `Ok(Some(answer))`, `Ok(None)` when the call reverted or answered no
/// well-formed bool (the contract does not implement ERC-165 properly), `Err` when the node could
/// not be asked (unknown, never "no").
fn supports<T: RpcTransport>(
    rpc: &RpcClient<T>,
    to: &str,
    id_hex: &str,
) -> Result<Option<bool>, String> {
    let mut data = selector("supportsInterface(bytes4)").to_vec();
    let id = hex::decode(id_hex).map_err(|_| "bad interface id".to_string())?;
    data.extend_from_slice(&id);
    data.extend(vec![0u8; 32usize.saturating_sub(id.len())]);
    let ret = match rpc.eth_call(call_to(to, &data)) {
        Ok(r) => r,
        Err(crate::rpc::RpcError::Node(_)) => return Ok(None),
        Err(e) => return Err(e.to_string()),
    };
    if ret.len() != 32 || ret[..31].iter().any(|&b| b != 0) || ret[31] > 1 {
        return Ok(None);
    }
    Ok(Some(ret[31] == 1))
}

fn read_word<T: RpcTransport>(rpc: &RpcClient<T>, to: &str, sig: &str) -> Option<Vec<u8>> {
    let ret = rpc.eth_call(call_to(to, &selector(sig))).ok()?;
    (ret.len() >= 32).then_some(ret)
}

fn read_short_string<T: RpcTransport>(rpc: &RpcClient<T>, to: &str, sig: &str) -> Option<String> {
    let ret = read_word(rpc, to, sig)?;
    let off = be_usize(&ret[..32]).ok()?;
    read_string_at(&ret, off)
        .ok()
        .map(|s| s.chars().take(64).collect())
}

fn erc20_guess<T: RpcTransport>(
    rpc: &RpcClient<T>,
    to: &str,
    consts: &BTreeSet<String>,
    is_nft: bool,
) -> Erc20Guess {
    let (present, missing): (Vec<_>, Vec<_>) = ERC20_SELECTORS
        .iter()
        .partition(|(_, s)| consts.contains(*s));
    let total_supply = read_word(rpc, to, "totalSupply()")
        .and_then(|b| word_u128(&b).ok())
        .map(|n| n.to_string());
    let decimals = read_word(rpc, to, "decimals()")
        .and_then(|b| (b[..31].iter().all(|&x| x == 0)).then_some(b[31]));
    let all = missing.is_empty();
    let verdict = if is_nft {
        "no"
    } else if all && total_supply.is_some() {
        "likely"
    } else if present.len() <= 2 {
        "no"
    } else {
        "unknown"
    };
    let (symbol, name) = if verdict == "no" {
        (None, None)
    } else {
        (
            read_short_string(rpc, to, "symbol()"),
            read_short_string(rpc, to, "name()"),
        )
    };
    Erc20Guess {
        verdict: verdict.to_string(),
        selectors_present: present.iter().map(|(n, _)| n.to_string()).collect(),
        selectors_missing: missing.iter().map(|(n, _)| n.to_string()).collect(),
        total_supply,
        decimals,
        symbol,
        name,
    }
}

/// `identify_contract(address)`.
pub fn identify<T: RpcTransport>(
    rpc: &RpcClient<T>,
    scan: &dyn ScanHttp,
    explorer_base: &str,
    address: &str,
) -> Result<Identity, String> {
    let info = get_code(rpc, scan, explorer_base, address)?;
    let b = bundles()?;
    let entries = &b.entries;
    let mut out = Identity {
        address: info.address.clone(),
        book_names: info.book_names.clone(),
        is_contract: info.is_contract,
        code_size: info.code_size,
        code_hash: info.code_hash.clone(),
        proxy: info.proxy.clone(),
        verified: info.verified.clone(),
        abi_source: "none".into(),
        abi_contract: None,
        erc165: "unknown".into(),
        interfaces: BTreeMap::new(),
        erc20: Erc20Guess {
            verdict: "no".into(),
            selectors_present: Vec::new(),
            selectors_missing: Vec::new(),
            total_supply: None,
            decimals: None,
            symbol: None,
            name: None,
        },
        known_selectors: Vec::new(),
        unknown_push4_count: 0,
        note: String::new(),
    };
    if !info.is_contract {
        out.note = "No code at this address, so there is no contract to identify.".into();
        return Ok(out);
    }
    let book_abi = book_abi_for(entries, &info.address).or_else(|| {
        info.proxy
            .as_ref()
            .and_then(|p| book_abi_for(entries, &p.implementation))
    });
    out.abi_source = match info.verified.status.as_str() {
        "verified" => "verified".into(),
        _ if book_abi.is_some() => "book".into(),
        "partial-match" => "partial-match".into(),
        _ => "none".into(),
    };
    if out.abi_source == "book" {
        out.abi_contract = book_abi;
    }
    // ERC-165: supportsInterface(0x01ffc9a7) is true and supportsInterface(0xffffffff) is false.
    out.erc165 = match (
        supports(rpc, &info.address, "01ffc9a7"),
        supports(rpc, &info.address, "ffffffff"),
    ) {
        (Ok(Some(true)), Ok(Some(false))) => "yes".into(),
        (Err(_), _) | (_, Err(_)) => "unknown".into(),
        _ => "no".into(),
    };
    if out.erc165 == "yes" {
        for (name, id) in INTERFACE_PROBES {
            let ans = match supports(rpc, &info.address, id) {
                Ok(Some(true)) => "yes",
                Ok(Some(false)) | Ok(None) => "no",
                Err(_) => "unknown",
            };
            out.interfaces.insert(name.to_string(), ans.to_string());
        }
    }
    let is_nft = out.interfaces.get("erc721").map(String::as_str) == Some("yes")
        || out.interfaces.get("erc1155").map(String::as_str) == Some("yes");
    // The selectors live in the implementation's code when this is a proxy.
    let code = match &info.proxy {
        Some(p) => get_code_bytes(rpc, &p.implementation)?,
        None => get_code_bytes(rpc, &info.address)?,
    };
    let consts = push4_constants(&code);
    out.erc20 = erc20_guess(rpc, &info.address, &consts, is_nft);
    for c in &consts {
        let key = format!("0x{c}");
        match b.functions.get(&key) {
            Some(frags) if !frags.is_empty() => {
                if out.known_selectors.len() < MAX_CODE_SELECTORS {
                    out.known_selectors.push(CodeSelector {
                        selector: key,
                        signatures: frags.clone(),
                    });
                }
            }
            _ => out.unknown_push4_count += 1,
        }
    }
    out.note = match (out.abi_source.as_str(), out.book_names.is_empty()) {
        ("verified", _) => "CitrateScan has verified source for this contract.".into(),
        ("book", false) => "A system contract from this build's address book; its bundled ABI is the one at genesis (CitrateScan has no verified source).".into(),
        ("book", true) => "A proxy whose implementation is a system contract in this build's address book.".into(),
        ("partial-match", _) => "CitrateScan has only a partial match: the shown source may differ from what was deployed.".into(),
        _ => "Not verified and not in this build's address book. The interfaces and selectors above are read from the code and calls; they are clues, not proof of what the contract does.".into(),
    };
    Ok(out)
}

fn book_abi_for(entries: &[BookEntry], address: &str) -> Option<String> {
    entries
        .iter()
        .find(|e| e.address == address && e.abi_contract.is_some())
        .and_then(|e| e.abi_contract.clone())
}

