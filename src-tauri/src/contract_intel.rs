/// The PUSH4 immediates in `code`, walking opcodes so PUSH data is never read as an opcode.
pub fn push4_constants(code: &[u8]) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut i = 0usize;
    while i < code.len() {
        let op = code[i];
        if (0x60..=0x7f).contains(&op) {
            let n = (op - 0x5f) as usize;
            if op == 0x63 && i + 5 <= code.len() {
                out.insert(hex::encode(&code[i + 1..i + 5]));
            }
            i += 1 + n;
        } else {
            i += 1;
        }
    }
    out
}

