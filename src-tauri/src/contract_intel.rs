/// One named address in the embedded book.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BookEntry {
    pub name: String,
    /// Lowercase `0x` address.
    pub address: String,
    /// The book section: contracts, aaStack, genesis, governance, precompiles or membership.
    pub section: String,
    /// The bundled ABI's contract (`path:Name`), when the bundle has one for this name.
    pub abi_contract: Option<String>,
    /// The book entry is a proxy in front of `abi_contract` (as deployed at genesis).
    pub proxy: bool,
}

struct Bundles {
    entries: Vec<BookEntry>,
    /// contract id (`path:Name`) -> ABI array.
    abis: BTreeMap<String, Value>,
    /// selector -> fragments; topic0 -> fragments; error selector -> fragments.
    functions: BTreeMap<String, Vec<String>>,
    events: BTreeMap<String, Vec<String>>,
    errors: BTreeMap<String, Vec<String>>,
}

fn bundles() -> Result<&'static Bundles, String> {
    static B: OnceLock<Result<Bundles, String>> = OnceLock::new();
    B.get_or_init(|| parse_bundles(CANONICAL_BOOK_JSON, SYSTEM_ABIS_JSON, SIGNATURES_JSON))
        .as_ref()
        .map_err(|e| e.clone())
}

fn fragments(v: Option<&Value>) -> BTreeMap<String, Vec<String>> {
    let mut out = BTreeMap::new();
    if let Some(map) = v.and_then(Value::as_object) {
        for (k, list) in map {
            let frags: Vec<String> = list
                .as_array()
                .map(|a| {
                    a.iter()
                        .filter_map(|f| f.get("fragment").and_then(Value::as_str))
                        .map(str::to_string)
                        .collect()
                })
                .unwrap_or_default();
            out.insert(k.to_ascii_lowercase(), frags);
        }
    }
    out
}

/// Parse the three embedded files. A malformed bundle is a build defect; it is reported as an
/// error by every tool rather than answered with an empty book.
fn parse_bundles(book_json: &str, abis_json: &str, sigs_json: &str) -> Result<Bundles, String> {
    let book: Value = serde_json::from_str(book_json)
        .map_err(|e| format!("the embedded address book is unreadable: {e}"))?;
    let abis: Value = serde_json::from_str(abis_json)
        .map_err(|e| format!("the bundled system ABIs are unreadable: {e}"))?;
    let sigs: Value = serde_json::from_str(sigs_json)
        .map_err(|e| format!("the bundled signature subset is unreadable: {e}"))?;
    let names = abis.get("contracts").and_then(Value::as_object);
    let abi_of = |name: &str| -> (Option<String>, bool) {
        let e = names.and_then(|m| m.get(name));
        (
            e.and_then(|x| x.get("contract"))
                .and_then(Value::as_str)
                .map(str::to_string),
            e.and_then(|x| x.get("proxy")).and_then(Value::as_bool) == Some(true),
        )
    };
    let mut entries: Vec<BookEntry> = Vec::new();
    let mut seen: BTreeSet<(String, String)> = BTreeSet::new();
    let mut push = |name: &str, addr: &str, section: &str| -> Result<(), String> {
        let address = normalize_address(addr)
            .map_err(|_| format!("the embedded address book has a bad address for {name}"))?;
        if seen.insert((name.to_string(), address.clone())) {
            let (abi_contract, proxy) = if section == "precompiles" {
                (None, false)
            } else {
                abi_of(name)
            };
            entries.push(BookEntry {
                name: name.to_string(),
                address,
                section: section.to_string(),
                abi_contract,
                proxy,
            });
        }
        Ok(())
    };
    for section in BOOK_SECTIONS {
        if let Some(map) = book.get(section).and_then(Value::as_object) {
            for (name, a) in map {
                if let Some(addr) = a.as_str() {
                    push(name, addr, section)?;
                }
            }
        }
    }
    // Top-level pins (CitrateMemberSBT, MembershipStakeVault); `deployer` is an account, not a
    // contract, and is left out.
    if let Some(map) = book.as_object() {
        for (name, a) in map {
            if name == "deployer" {
                continue;
            }
            if let Some(addr) = a.as_str().filter(|s| s.len() == 42 && s.starts_with("0x")) {
                push(name, addr, "membership")?;
            }
        }
    }
    let abis_map: BTreeMap<String, Value> = abis
        .get("abis")
        .and_then(Value::as_object)
        .map(|m| m.iter().map(|(k, v)| (k.clone(), v.clone())).collect())
        .unwrap_or_default();
    Ok(Bundles {
        entries,
        abis: abis_map,
        functions: fragments(sigs.get("functions")),
        events: fragments(sigs.get("events")),
        errors: fragments(sigs.get("errors")),
    })
}

/// Every entry of the embedded book.
pub fn book_entries() -> Result<&'static [BookEntry], String> {
    bundles().map(|b| b.entries.as_slice())
}

/// The book names of `address` (lowercase `0x`), possibly several (an alias such as GOVERNANCE).
pub fn names_for(entries: &[BookEntry], address: &str) -> Vec<String> {
    entries
        .iter()
        .filter(|e| e.address == address)
        .map(|e| e.name.clone())
        .collect()
}

fn squash(s: &str) -> String {
    s.chars()
        .filter(|c| c.is_ascii_alphanumeric())
        .map(|c| c.to_ascii_lowercase())
        .collect()
}

/// Book entries matching `query`: by address (exact), else by name (exact, prefix, substring,
/// then every word of the query), best first.
pub fn search_book(entries: &[BookEntry], query: &str) -> Vec<BookEntry> {
    if let Ok(addr) = normalize_address(query) {
        return entries
            .iter()
            .filter(|e| e.address == addr)
            .cloned()
            .collect();
    }
    let q = squash(query);
    if q.is_empty() {
        return Vec::new();
    }
    let words: Vec<String> = query
        .split(|c: char| !c.is_ascii_alphanumeric())
        .map(squash)
        .filter(|w| w.len() >= 2)
        .collect();
    let mut scored: Vec<(u8, &BookEntry)> = entries
        .iter()
        .filter_map(|e| {
            let n = squash(&e.name);
            let score = if n == q {
                4
            } else if n.starts_with(&q) {
                3
            } else if n.contains(&q) {
                2
            } else if !words.is_empty() && words.iter().all(|w| n.contains(w.as_str())) {
                1
            } else {
                0
            };
            (score > 0).then_some((score, e))
        })
        .collect();
    scored.sort_by(|a, b| b.0.cmp(&a.0).then_with(|| a.1.name.cmp(&b.1.name)));
    scored
        .into_iter()
        .take(MAX_BOOK_MATCHES)
        .map(|(_, e)| e.clone())
        .collect()
}

