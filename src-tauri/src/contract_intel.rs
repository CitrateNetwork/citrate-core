/// What `contract_abi_resolve` returns.
#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct AbiResolution {
    pub address: String,
    /// verified | book | partial-match | none
    pub source: String,
    /// The address whose ABI this is (the proxy's implementation, when that answered).
    pub abi_address: Option<String>,
    pub contract_name: Option<String>,
    pub abi: Option<Value>,
    pub proxy: Option<ProxyInfo>,
    pub book_names: Vec<String>,
    pub note: String,
}

/// Resolve the ABI to decode calls to `address`: verified (address, then implementation), then
/// the bundled book ABI (address, then implementation), then a partial match.
pub fn resolve_abi<T: RpcTransport>(
    rpc: &RpcClient<T>,
    scan: &dyn ScanHttp,
    explorer_base: &str,
    address: &str,
) -> Result<AbiResolution, String> {
    let address = normalize_address(address)?;
    let b = bundles()?;
    let code = get_code_bytes(rpc, &address)?;
    let proxy = detect_proxy(rpc, &b.entries, &address, &code)?;
    let mut targets = vec![address.clone()];
    if let Some(p) = &proxy {
        targets.push(p.implementation.clone());
    }
    let mut out = AbiResolution {
        book_names: names_for(&b.entries, &address),
        address: address.clone(),
        source: "none".into(),
        abi_address: None,
        contract_name: None,
        abi: None,
        proxy: proxy.clone(),
        note: String::new(),
    };
    if code.is_empty() {
        out.note = "No code at this address, so there is no ABI.".into();
        return Ok(out);
    }
    let mut partial: Option<(String, crate::verified_source::VerifiedSource)> = None;
    let mut explorer_errors = Vec::new();
    for t in &targets {
        match crate::verified_source::lookup(scan, explorer_base, t) {
            Ok(v) if v.status == "verified" && v.abi.is_some() => {
                out.source = "verified".into();
                out.abi_address = Some(t.clone());
                out.contract_name = v.contract_name;
                out.abi = v.abi;
                out.note = format!("CitrateScan's verified ABI for {t}.");
                return Ok(out);
            }
            Ok(v) if v.status == "partial-match" && v.abi.is_some() && partial.is_none() => {
                partial = Some((t.clone(), v));
            }
            Ok(_) => {}
            Err(e) => explorer_errors.push(e),
        }
    }
    for t in &targets {
        if let Some(id) = book_abi_for(&b.entries, t) {
            if let Some(abi) = b.abis.get(&id) {
                out.source = "book".into();
                out.abi_address = Some(t.clone());
                out.contract_name = id.rsplit(':').next().map(str::to_string);
                out.abi = Some(abi.clone());
                out.note = format!("The bundled system ABI of {id} (from this build's address book; the ABI at genesis).");
                return Ok(out);
            }
        }
    }
    if let Some((t, v)) = partial {
        out.source = "partial-match".into();
        out.abi_address = Some(t.clone());
        out.contract_name = v.contract_name;
        out.abi = v.abi;
        out.note = format!(
            "Only a partial match on CitrateScan for {t}: names may differ from the deployed code."
        );
        return Ok(out);
    }
    out.note = if explorer_errors.is_empty() {
        "No verified or bundled ABI for this contract; only the bundled signature subset can decode it.".into()
    } else {
        format!(
            "No bundled ABI, and CitrateScan could not be read ({}); only the bundled signature subset can decode it.",
            explorer_errors.join("; ")
        )
    };
    Ok(out)
}

/// What `abi_signature_lookup` returns: each requested key with the fragments that match it.
#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SignatureMatches {
    pub functions: BTreeMap<String, Vec<String>>,
    pub events: BTreeMap<String, Vec<String>>,
    pub errors: BTreeMap<String, Vec<String>>,
}

fn hex_key(s: &str, bytes: usize) -> Result<String, String> {
    let t = s.trim().to_ascii_lowercase();
    let h = t.strip_prefix("0x").unwrap_or(&t);
    if h.len() != bytes * 2 || !h.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err(format!(
            "expected 0x followed by {} hex digits, got {s}",
            bytes * 2
        ));
    }
    Ok(format!("0x{h}"))
}

/// Look `selectors` (4 bytes: functions and errors) and `topics` (32 bytes: events) up in the
/// bundled subset. A key with no match maps to an empty list (unknown, never guessed).
pub fn lookup_signatures(
    selectors: &[String],
    topics: &[String],
) -> Result<SignatureMatches, String> {
    if selectors.len() + topics.len() > MAX_SIGNATURE_KEYS {
        return Err(format!(
            "at most {MAX_SIGNATURE_KEYS} selectors and topics per lookup"
        ));
    }
    let b = bundles()?;
    let mut out = SignatureMatches {
        functions: BTreeMap::new(),
        events: BTreeMap::new(),
        errors: BTreeMap::new(),
    };
    for s in selectors {
        let k = hex_key(s, 4)?;
        out.functions
            .insert(k.clone(), b.functions.get(&k).cloned().unwrap_or_default());
        out.errors
            .insert(k.clone(), b.errors.get(&k).cloned().unwrap_or_default());
    }
    for t in topics {
        let k = hex_key(t, 32)?;
        out.events
            .insert(k.clone(), b.events.get(&k).cloned().unwrap_or_default());
    }
    Ok(out)
}

