//! CORE-A1 / CORE-A2 — Hermes can find, read and identify contracts.
//!
//! Read-only agent tools over chain 40204. Nothing here signs, holds a key or sends a
//! transaction; every answer says where it came from, and what could not be read is reported as
//! unknown, never filled in.
//!
//! ## Data sources (Rule 7, named per tool)
//! - **`address_book_lookup`**: the canonical 40204 address book embedded at build time
//!   (`addresses/40204.canonical.json`, copied next to the generated book by
//!   `scripts/sync-addresses.py` from citrate-chain `contracts/addresses/40204.json`), plus live
//!   `eth_call` reads of the on-chain registries named in that book: `ModelRegistry`
//!   (`getAllModelHashes`/`getModel`, `getModelsByOwner`), `SkillRegistry`
//!   (`getAllSkillHashes`/`getSkill`, `getSkillsByOwner`) and `AgentSBT` (`balanceOf`).
//!   `CapsuleRegistry` keys capsules by numeric id with no name or owner index, so it is reported
//!   as not searchable rather than scanned.
//! - **`get_code`**: `eth_getCode`, `eth_getStorageAt` (EIP-1967 implementation / beacon slots,
//!   EIP-1822 slot) and `eth_call implementation()` on a beacon, on the 40204 RPC; the EIP-1167
//!   minimal-proxy pattern read from the code itself; verified status from CitrateScan's
//!   verified-source lookup ([`crate::verified_source::lookup`]).
//! - **`identify_contract`**: everything `get_code` reads, plus ERC-165 `supportsInterface`
//!   probes and ERC-20 reads (`totalSupply`, `decimals`, `symbol`, `name`) by `eth_call`, and the
//!   PUSH4 constants in the runtime code matched against the bundled signature subset.
//! - **`contract_abi_resolve`** (decoding, CORE-A2): the ABI used to decode, in this order: the
//!   explorer's verified ABI, then the bundled system ABI of a book contract
//!   (`abis/40204.system-abis.json`), then a partial-match ABI from the explorer. A proxy's
//!   implementation is tried after the address itself.
//! - **`abi_signature_lookup`**: the bundled selector/topic subset (`abis/signatures.json`),
//!   generated by `scripts/gen-system-abis.mjs` from the bundled ABIs plus a small curated set of
//!   standard interfaces. No signature service is asked at runtime.
//! - **`chain_tx_fetch`**: `eth_getTransactionByHash` and `eth_getTransactionReceipt` on the
//!   40204 RPC.
//!
//! Decoding itself (calldata, logs, the tx explanation) runs in the webview with viem
//! (`src/agent/contractIntel.ts`) over what these commands return.

