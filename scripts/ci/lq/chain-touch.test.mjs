describe("lq / chain-touch: policy 3 (the lockfile closure of the chain crates)", () => {
  it("lock closure change is class C", async () => {
    const dir = fixture();
    change(dir, { "Cargo.lock": lock("0.13.5") });
    const r = await check(dir, { branch: "feat/v60-l3-wp02-shell" });
    expect(r.ok).toBe(false);
    const c = r.classC.find((x) => x.path === "Cargo.lock");
    expect(c).toBeTruthy();
    expect(c.detail).toMatch(/k256/);
  });

  it("a lockfile change outside the closure is not class C", async () => {
    const dir = fixture();
    change(dir, { "Cargo.lock": lock("0.13.4", "1.0.229") });
    const r = await check(dir, { branch: "feat/v60-l3-wp02-shell" });
    expect(r.classC).toEqual([]);
    expect(r.ok).toBe(true);
  });

  it("an unparsable lockfile is class C (fail closed)", async () => {
    const dir = fixture();
    change(dir, { "Cargo.lock": "[[package]]\nname = \"citrate-wallet-core\"\ndependencies = [\n \"k256\",\n" });
    const r = await check(dir, { branch: "feat/v60-l3-wp02-shell" });
    expect(r.classC.map((c) => c.path)).toContain("Cargo.lock");
  });

  it("closure follows versioned dependency names to the exact package", () => {
    const pk = parseLock(lock());
    expect(pk.map((p) => `${p.name} ${p.version}`)).toContain("sha3 0.9.1");
    const cl = lockClosure(lock(), ["citrate-wallet-core"], "citrate-chain");
    expect(cl.some((l) => l.startsWith("sha3 0.10.8 "))).toBe(true);
    expect(cl.some((l) => l.startsWith("sha3 0.9.1 "))).toBe(false);
    expect(cl.some((l) => l.startsWith("serde "))).toBe(false);
  });
});

