    const dir = fixture();
    const head = repin(dir, "rules-2");
    const r = await check(dir, { branch: "feat/v60-l0-wp03-one-chain-rev", labels: ["chain-touch", "consensus-review"], checkRuns: AGREEMENT_GREEN, headSha: head, reviews: [approve("BerryManifold", head), approve("Matr0xshka", head)] });
