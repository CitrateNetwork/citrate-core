const fingerprint = (rev, rules) => JSON.stringify({ rev, tree: "t", rules_fp: rules, node_fp: `n-${rev.slice(0, 6)}`, toolchain: "1.99.1", lock_fp: "l" });

function evidence(rev, rules) {
  const d = `release/evidence/chain/${rev.slice(0, 12)}`;
  return {
    [`${d}/source-fingerprint.json`]: fingerprint(rev, rules),
    [`${d}/agreement-x86_64.json`]: JSON.stringify({ rev, arch: "x86_64" }),
    [`${d}/agreement-aarch64.json`]: JSON.stringify({ rev, arch: "aarch64" }),
    [`${d}/bench.md`]: "---\ncreated: 2026-11-27\nbranch: feat/v60-l0-wp03\nauthor: test\nstatus: final\n---\n\n# bench\n",
  };
}

const tmps = [];
afterEach(() => { while (tmps.length) fs.rmSync(tmps.pop(), { recursive: true, force: true }); });

const git = (dir, ...a) => execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@example.invalid", "-c", "commit.gpgsign=false", ...a], { cwd: dir, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

function write(dir, files) {
  for (const [rel, body] of Object.entries(files)) {
    const p = path.join(dir, rel);
    if (body === null) { fs.rmSync(p, { force: true }); continue; }
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, body);
  }
}

// Base: the real map and reviewer set, a node pin with base evidence, a lockfile and the class C
// files a lane might touch. Returns a repo whose HEAD is the base; call change() for the branch.
function fixture(baseExtra = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "lq-chain-touch-"));
  tmps.push(dir);
  git(dir, "init", "-q", "-b", "main");
  write(dir, {
    "release/chain-touch.json": fs.readFileSync(path.join(repo, "release", "chain-touch.json"), "utf8"),
    "release/consensus-reviewers.json": fs.readFileSync(path.join(repo, "release", "consensus-reviewers.json"), "utf8"),
    "release/components.json": components(),
    "release/network-cut.json": JSON.stringify({ genesisHash: "0xcf68", chainRev: BASE_REV.slice(0, 8) }),
    "Cargo.lock": lock(),
    "src-tauri/Cargo.toml": tauriToml(),
    "src-tauri/src/node.rs": "pub const NODE_VALIDATOR_ACTIVATION_HEIGHT: &str = \"2000\";\n",
    "src-tauri/src/model.rs": "pub fn model() {}\n",
    "src-tauri/runtime-deps.sha256": `${"11".repeat(32)}  citrate-x86_64-unknown-linux-gnu-${BASE_REV.slice(0, 12)}\n${"22".repeat(32)}  kubo-x86_64-unknown-linux-gnu\n`,
    "docs/notes.md": "# notes\n",
    ...evidence(BASE_REV, "rules-1"),
    ...baseExtra,
  });
  git(dir, "add", "-A");
  git(dir, "commit", "-q", "-m", "base");
  git(dir, "tag", "base");
  return dir;
}

function change(dir, files) {
  write(dir, files);
  git(dir, "add", "-A");
  git(dir, "commit", "-q", "-m", "change");
  return git(dir, "rev-parse", "HEAD").trim();
}

const approve = (login, commit_id, state = "APPROVED") => ({ user: { login }, state, commit_id, submitted_at: "2026-11-27T01:00:00Z" });

async function check(dir, ctx) {
  return runCheck({ root: dir, base: "base", head: "HEAD", labels: [], reviews: [], checkRuns: [], ...ctx });
}

// A full L0 re-pin: node rev and the chain dep move to NEW_REV with evidence.
function repin(dir, rules = "rules-1") {
  return change(dir, {
    "release/components.json": components({ rev: NEW_REV }),
    "src-tauri/Cargo.toml": tauriToml(NEW_REV),
    ...evidence(NEW_REV, rules),
  });
}

