// Writes .github/CODEOWNERS from .agentile/v60-ownership.map (one source, Rule 9).
//
//   node scripts/gen-codeowners.mjs           # rewrite .github/CODEOWNERS
//   node scripts/gen-codeowners.mjs --check   # exit 1 if the committed file differs
//
// Map rows keep their order: CODEOWNERS and scripts/cx-ownership-check.sh --map v60 both let the
// last matching row win. A glob CODEOWNERS cannot express with the same meaning the matcher gives
// it is refused, so the two can never disagree about who owns a path. 'create:<lanes>' seed rows
// grant no ownership, so they are checked like any glob and left out of CODEOWNERS.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const LANE = /^(l[0-9]|lq|frozen)$/;

export function parseMap(text) {
  const rows = [];
  const creates = [];
  const reviewers = new Map();
  const tail = [];
  text.split("\n").forEach((raw, i) => {
    const line = raw.trim();
    const where = `v60-ownership.map:${i + 1}`;
    if (line.startsWith("#!")) {
      const [kind, key, ...owners] = line.slice(2).trim().split(/\s+/);
      if (!owners.length || !owners.every((o) => /^@[\w.-]+(\/[\w.-]+)?$/.test(o))) {
        throw new Error(`${where}: directive needs owners like @org/team or @user`);
      }
      if (kind === "reviewers") reviewers.set(key, owners);
      else if (kind === "tail") tail.push({ pattern: key, owners });
      else throw new Error(`${where}: unknown directive '${kind}'`);
      return;
    }
    if (!line || line.startsWith("#")) return;
    const parts = line.split(/\s+/);
    if (parts.length !== 2) throw new Error(`${where}: want '<lanes> <glob>', got '${line}'`);
    const seed = parts[0].startsWith("create:");
    const lanes = (seed ? parts[0].slice(7) : parts[0]).split(",");
    if (!((!seed && parts[0] === "*") || lanes.every((l) => LANE.test(l) && !(seed && l === "frozen")))) {
      throw new Error(`${where}: unknown lane list '${parts[0]}'`);
    }
    try {
      toCodeownersPattern(parts[1]);
    } catch (e) {
      throw new Error(`${where}: ${e.message}`);
    }
    (seed ? creates : rows).push({ lanes, glob: parts[1], line: i + 1 });
  });
  if (!reviewers.has("*")) throw new Error("v60-ownership.map: missing '#! reviewers * ...'");
  return { rows, creates, reviewers, tail };
}

// Map glob -> CODEOWNERS pattern with the same meaning, or throw.
export function toCodeownersPattern(glob) {
  if (glob === "**") return "*";
  if (/[\s[\]{}?!\\#]/.test(glob) || glob.startsWith("/")) {
    throw new Error(`glob '${glob}': characters CODEOWNERS treats differently`);
  }
  if (glob.endsWith("/")) throw new Error(`glob '${glob}': CODEOWNERS reads a trailing '/' as a directory; write '${glob}**'`);
  const body = glob.endsWith("/**") ? glob.slice(0, -3) : glob;
  if (body.includes("**")) throw new Error(`glob '${glob}': '**' only as the whole glob or a trailing '/**'`);
  if (!body) throw new Error(`glob '${glob}': empty path`);
  return `/${glob}`;
}

export function generate(mapText) {
  const { rows, reviewers, tail } = parseMap(mapText);
  const ownersFor = (lanes) => {
    const set = new Set();
    for (const l of lanes) for (const o of reviewers.get(l) ?? reviewers.get("*")) set.add(o);
    return [...set].join(" ");
  };
  const out = [
    "# GENERATED by scripts/gen-codeowners.mjs from .agentile/v60-ownership.map. Do not edit by hand:",
    "# change the map, run `node scripts/gen-codeowners.mjs`, commit both (codeowners.test.mjs checks).",
    "# Team: https://github.com/orgs/CitrateNetwork/teams/maintainers",
    "# The last matching rule wins. A comment above each run of rules names the owning lane.",
  ];
  let last = "";
  for (const r of rows) {
    if (r.lanes[0] === "*") continue; // always-allowed process files keep the default owners
    const label = r.lanes.join(",");
    if (label !== last) {
      out.push("", `# ${label}`);
      last = label;
    }
    out.push(`${toCodeownersPattern(r.glob)} ${ownersFor(r.lanes)}`);
  }
  if (tail.length) {
    out.push(
      "",
      "# Owner-pinned paths (map '#! tail'), written last so no lane rule above overrides them. V60",
      "# MESH-2: the CL-S4 sign-off record, the packet copy and the signer registry need the owner's",
      "# approval; the security lead's part is their signature in the record, checked against signers.json.",
    );
    for (const t of tail) out.push(`${t.pattern} ${t.owners.join(" ")}`);
  }
  return out.join("\n") + "\n";
}

function main() {
  const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const target = path.join(repo, ".github/CODEOWNERS");
  const want = generate(readFileSync(path.join(repo, ".agentile/v60-ownership.map"), "utf8"));
  if (process.argv.includes("--check")) {
    let have = "";
    try {
      have = readFileSync(target, "utf8");
    } catch {
      have = "";
    }
    if (have !== want) {
      console.error("CODEOWNERS is stale: run `node scripts/gen-codeowners.mjs` and commit the result.");
      process.exit(1);
    }
    console.log("CODEOWNERS matches .agentile/v60-ownership.map");
    return;
  }
  writeFileSync(target, want);
  console.log(`wrote ${path.relative(repo, target)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
