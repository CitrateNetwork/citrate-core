#!/usr/bin/env node
// =====================================================================
// citrate-core — generate the bundled system ABIs and the signature subset (CORE-A2).
//
// Hermes decodes calldata and logs with, in order: the explorer's verified ABI, then the ABI of
// a system contract named in the address book, then a selector/topic signature subset. The
// last two are bundled in the app, so they are GENERATED here, never hand-written:
//
//   src-tauri/abis/40204.system-abis.json  book name -> {contract, abi} for every book entry
//                                          whose Solidity source is known (NAME_MAP below)
//   src-tauri/abis/signatures.json         4-byte selector / topic0 -> fragments, built from
//                                          those ABIs plus a small curated standard set
//                                          (ERC-20/721/1155/165, Ownable, AccessControl,
//                                          proxies, Pausable, WETH, Multicall)
//
// Data source: the citrate-chain Solidity sources at a named rev, compiled ABI-only (solc
// standard JSON, outputSelection = abi, so no code generation runs and no optimizer or via-IR
// setting can change the result), and the canonical address book next to the generated one
// (`src-tauri/addresses/40204.canonical.json`, written by scripts/sync-addresses.py). No
// network: nothing is fetched from 4byte or any signature service.
//
// Usage (from the repo root):
//   node scripts/gen-system-abis.mjs --contracts <citrate-chain>/contracts --chain-rev <sha> \
//     --solc <path to solc 0.8.36>
//   node scripts/gen-system-abis.mjs --solc-output <solc standard-JSON output> --chain-rev <sha>
//
// `--contracts` needs that checkout's lib/ submodules populated (OpenZeppelin, account-abstraction,
// kernel); `forge remappings` is read from it for the import map.
// =====================================================================
import { execFileSync } from "node:child_process";
