import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { formatAbiItem as canonicalAbiItem, toEventSelector, toFunctionSelector } from "viem/utils";
import { parseAbiItem } from "viem";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BOOK = join(ROOT, "src-tauri/addresses/40204.canonical.json");
const OUT_DIR = join(ROOT, "src-tauri/abis");
export const GENERATED_MARKER = "GENERATED by scripts/gen-system-abis.mjs";

