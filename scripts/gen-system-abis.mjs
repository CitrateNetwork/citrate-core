function args(argv) {
  const out = {};
  for (let i = 2; i < argv.length; i += 2) {
    const k = argv[i];
    if (!k.startsWith("--")) throw new Error(`unexpected argument ${k}`);
    out[k.slice(2)] = argv[i + 1];
  }
  return out;
}

function solFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...solFiles(p));
    else if (name.endsWith(".sol")) out.push(p);
  }
  return out;
}

/** Compile the contracts checkout ABI-only with solc's standard JSON; returns the parsed output. */
function compileAbis(contractsDir, solc) {
  const remappings = execFileSync("forge", ["remappings"], { cwd: contractsDir, encoding: "utf8" })
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  const sources = {};
  for (const p of solFiles(join(contractsDir, "src"))) sources[relative(contractsDir, p)] = { urls: [relative(contractsDir, p)] };
  for (const p of [
    "lib/account-abstraction/contracts/core/EntryPoint.sol",
    "lib/openzeppelin-contracts/contracts/governance/TimelockController.sol",
  ]) {
    sources[p] = { urls: [p] };
  }
  const input = {
    language: "Solidity",
    sources,
    settings: { remappings, evmVersion: "cancun", outputSelection: { "*": { "*": ["abi"] } } },
  };
  const out = execFileSync(solc, ["--standard-json", "--allow-paths", ".", "--base-path", "."], {
    cwd: contractsDir,
    input: JSON.stringify(input),
    encoding: "utf8",
    maxBuffer: 1 << 30,
  });
  return JSON.parse(out);
}

/** contract name -> [{path, abi}] from a solc standard-JSON output. */
export function indexContracts(solcOut) {
  const errs = (solcOut.errors ?? []).filter((e) => e.severity === "error");
  if (errs.length) throw new Error(`solc reported ${errs.length} errors; first: ${errs[0].formattedMessage}`);
  const byName = new Map();
  for (const [path, cs] of Object.entries(solcOut.contracts ?? {})) {
    for (const [name, c] of Object.entries(cs)) {
      if (!byName.has(name)) byName.set(name, []);
      byName.get(name).push({ path, abi: c.abi });
    }
  }
  return byName;
}

/** Every (name, address) in the canonical book's contract sections, plus its top-level pins. */
export function bookEntries(book) {
  const out = [];
  for (const section of BOOK_SECTIONS) {
    for (const [name, address] of Object.entries(book[section] ?? {})) out.push({ name, address: address.toLowerCase(), section });
  }
  for (const [name, v] of Object.entries(book)) {
    if (typeof v === "string" && /^0x[0-9a-fA-F]{40}$/.test(v) && name !== "deployer") out.push({ name, address: v.toLowerCase(), section: "top" });
  }
  return out;
}

function pick(byName, contract) {
  const all = byName.get(contract) ?? [];
  const src = all.filter((c) => c.path.startsWith("src/"));
  const list = src.length ? src : all;
  if (list.length === 0) return null;
  if (list.length > 1) throw new Error(`contract ${contract} is defined in ${list.map((c) => c.path).join(", ")}; name one in NAME_MAP`);
  return list[0];
}

/** Book name -> {contract, proxy?, abi | null, note?}. Unknown sources are left out, not guessed. */
export function systemAbis(entries, byName) {
  const out = {};
  const missing = [];
  for (const { name } of entries) {
    if (out[name]) continue;
    const m = NAME_MAP[name] ?? (name.startsWith(TEAM_VESTING_PREFIX) ? { contract: "TeamVestingWallet" } : { contract: name });
    if (m.abi === null) {
      out[name] = { contract: null, abi: null, note: m.note };
      continue;
    }
    const c = pick(byName, m.contract);
    if (!c) {
      missing.push(name);
      continue;
    }
    out[name] = { contract: `${c.path}:${m.contract}`, ...(m.proxy ? { proxy: true } : {}), abi: c.abi };
  }
  return { abis: out, missing };
}

/** Drop solc's `internalType` (Solidity-side names, not part of the ABI encoding) to keep the
 *  bundle small; everything a decoder reads (type, name, indexed, components) stays. */
function lean(x) {
  if (Array.isArray(x)) return x.map(lean);
  if (x && typeof x === "object") {
    const o = {};
    for (const [k, v] of Object.entries(x)) if (k !== "internalType") o[k] = lean(v);
    return o;
  }
  return x;
}

/** The bundle shape: each ABI once (by contract id), and each book name pointing at one. */
export function bundle(abis) {
  const contracts = {};
  const byId = {};
  for (const [name, e] of Object.entries(abis)) {
    contracts[name] = { contract: e.contract, ...(e.proxy ? { proxy: true } : {}), ...(e.note ? { note: e.note } : {}) };
    if (e.contract && !byId[e.contract]) byId[e.contract] = lean(e.abi);
  }
  return { contracts, abis: byId };
}

function canonicalSig(item) {
  return canonicalAbiItem(item);
}

/** The signature subset: selector -> function fragments, topic0 -> event fragments, selector -> errors. */
export function signatureSubset(abis) {
  const functions = new Map();
  const events = new Map();
  const errors = new Map();
  const add = (map, key, fragment, sig, origin) => {
    if (!map.has(key)) map.set(key, new Map());
    const byFrag = map.get(key);
    if (!byFrag.has(fragment)) byFrag.set(fragment, { sig, fragment, from: new Set() });
    byFrag.get(fragment).from.add(origin);
  };
  /** One fragment per distinct shape: names dropped from events would lose `indexed`, so keep them. */
  const visit = (item, origin) => {
    if (item.type === "function") {
      const sig = canonicalSig(item);
      add(functions, toFunctionSelector(sig), shape(item), sig, origin);
    } else if (item.type === "event" && !item.anonymous) {
      const sig = canonicalSig(item);
      add(events, toEventSelector(sig), shape(item), sig, origin);
    } else if (item.type === "error") {
      const sig = canonicalSig(item);
      add(errors, toFunctionSelector(sig), shape(item), sig, origin);
    }
  };
  for (const [group, list] of Object.entries(STANDARD_SET)) for (const s of list) visit(parseAbiItem(s), group);
  for (const [name, entry] of Object.entries(abis)) for (const item of entry.abi ?? []) visit(item, name);
  const flat = (map) =>
    Object.fromEntries(
      [...map.entries()]
        .sort(([a], [b]) => (a < b ? -1 : 1))
        .map(([k, byFrag]) => [k, [...byFrag.values()].map((v) => ({ sig: v.sig, fragment: v.fragment, from: [...v.from].sort() }))]),
    );
  return { functions: flat(functions), events: flat(events), errors: flat(errors) };
}

function param(p) {
  const base = p.type.startsWith("tuple") ? `(${(p.components ?? []).map(param).join(", ")})${p.type.slice(5)}` : p.type;
  return `${base}${p.indexed ? " indexed" : ""}${p.name ? ` ${p.name}` : ""}`;
}

/**
 * A human-readable fragment with parameter names and (for events) `indexed`. It must parse back
 * (viem `parseAbiItem`) to the same canonical signature, or generation fails: the app parses
 * these at runtime to decode.
 */
export function shape(item) {
  const params = `(${(item.inputs ?? []).map(param).join(", ")})`;
  let text;
  if (item.type === "function") {
    const m = item.stateMutability && item.stateMutability !== "nonpayable" ? ` ${item.stateMutability}` : "";
    const outs = item.outputs?.length ? ` returns (${item.outputs.map(param).join(", ")})` : "";
    text = `function ${item.name}${params}${m}${outs}`;
  } else {
    text = `${item.type} ${item.name}${params}`;
  }
  const back = parseAbiItem(text);
  if (canonicalAbiItem(back) !== canonicalAbiItem(item)) throw new Error(`fragment does not round-trip: ${text}`);
  return text;
}

export function generate({ solcOut, book, chainRev }) {
  const byName = indexContracts(solcOut);
  const entries = bookEntries(book);
  const { abis, missing } = systemAbis(entries, byName);
  if (missing.length) throw new Error(`no Solidity source found for book entries: ${missing.join(", ")}; add them to NAME_MAP`);
  const sigs = signatureSubset(abis);
  const header = {
    _comment: `${GENERATED_MARKER} from citrate-chain contracts at ${chainRev} (ABI-only solc compile) and src-tauri/addresses/40204.canonical.json. Do not hand-edit; re-run the script.`,
    chainId: book.chainId,
    chainRev,
  };
  return {
    systemAbis: { ...header, ...bundle(abis) },
    signatures: { ...header, standardSet: Object.keys(STANDARD_SET), ...sigs },
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const a = args(process.argv);
  if (!a["chain-rev"] || !/^[0-9a-f]{7,40}$/.test(a["chain-rev"])) throw new Error("--chain-rev <citrate-chain sha> is required");
  const solcOut = a["solc-output"]
    ? JSON.parse(readFileSync(a["solc-output"], "utf8"))
    : compileAbis(resolve(a.contracts ?? ""), a.solc ?? "solc");
  const book = JSON.parse(readFileSync(BOOK, "utf8"));
  const { systemAbis: s, signatures } = generate({ solcOut, book, chainRev: a["chain-rev"] });
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, "40204.system-abis.json"), JSON.stringify(s) + "\n");
  writeFileSync(join(OUT_DIR, "signatures.json"), JSON.stringify(signatures, null, 0) + "\n");
  const nf = Object.keys(signatures.functions).length;
  const ne = Object.keys(signatures.events).length;
  console.log(`system ABIs: ${Object.keys(s.contracts).length} book names, ${Object.keys(s.abis).length} ABIs; signatures: ${nf} selectors, ${ne} event topics`);
}
