// Writes src/shell/flags.gen.ts from release/flags.json (one source, Rule 9), so the webview reads
// the same build-time flag values the Rust consts hold (src-tauri/src/flags_tests.rs ties
// the table to the consts).
//
//   node scripts/gen-flags.mjs           # rewrite src/shell/flags.gen.ts
//   node scripts/gen-flags.mjs --check   # exit 1 if the committed file differs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const TABLE = "release/flags.json";
export const OUT = "src/shell/flags.gen.ts";

const IDENT = /^[A-Z][A-Z0-9_]*$/;
const LANE = /^l[0-9]$/;

// The fields the webview gets. File paths and packet repos stay out of the bundle.
function row(r, i) {
  const at = `${TABLE} flags[${i}]`;
  if (!r || typeof r !== "object") throw new Error(`${at}: not an object`);
  if (typeof r.name !== "string" || !IDENT.test(r.name)) throw new Error(`${at}: name must be SCREAMING_CASE`);
  if (typeof r.default !== "boolean") throw new Error(`${at} ${r.name}: default must be true or false`);
  if (typeof r.lane !== "string" || !LANE.test(r.lane)) throw new Error(`${at} ${r.name}: lane must be l0..l9`);
  if (typeof r.summary !== "string" || !r.summary.trim()) throw new Error(`${at} ${r.name}: summary is required`);
  const signoff = r.signoff == null ? null : r.signoff.id;
  if (signoff !== null && (typeof signoff !== "string" || !signoff)) throw new Error(`${at} ${r.name}: signoff.id is required`);
  return { name: r.name, lane: r.lane, default: r.default, signoff, summary: r.summary };
}

export function render(text) {
  const table = JSON.parse(text);
  if (!Array.isArray(table?.flags)) throw new Error(`${TABLE}: missing flags array`);
  const rows = table.flags.map(row);
  const names = new Set();
  for (const r of rows) {
    if (names.has(r.name)) throw new Error(`${TABLE}: ${r.name} is listed twice`);
    names.add(r.name);
  }
  const s = JSON.stringify;
  const lines = [
    `// GENERATED by scripts/gen-flags.mjs from ${TABLE}. Do not edit; run \`node scripts/gen-flags.mjs\`.`,
    "// L0-WP09: the build-time feature flags. A flag with a sign-off is true only with a verified",
    "// record in release/signoffs/ (checked by cargo test, src-tauri/src/flags_tests.rs).",
    "",
    "/** One build-time flag: its owning lane, its value in this build, and the sign-off it needs. */",
    "export interface FlagRow {",
    "  readonly name: string;",
    "  readonly lane: string;",
    "  readonly default: boolean;",
    "  readonly signoff: string | null;",
    "  readonly summary: string;",
    "}",
    "",
    "export const FLAG_ROWS: readonly FlagRow[] = [",
    ...rows.map(
      (r) =>
        `  { name: ${s(r.name)}, lane: ${s(r.lane)}, default: ${r.default}, signoff: ${s(r.signoff)}, summary: ${s(r.summary)} },`,
    ),
    "];",
    "",
    "/** Each flag's value in this build. */",
    "export const FLAGS = {",
    ...rows.map((r) => `  ${r.name}: ${r.default},`),
    "} as const;",
    "",
  ];
  return lines.join("\n");
}

function main(argv, root) {
  const want = render(readFileSync(path.join(root, TABLE), "utf8"));
  const out = path.join(root, OUT);
  if (argv.includes("--check")) {
    let have = "";
    try {
      have = readFileSync(out, "utf8");
    } catch {
      have = "";
    }
    if (have !== want) {
      console.error(`${OUT} is stale; run node scripts/gen-flags.mjs`);
      return 1;
    }
    return 0;
  }
  writeFileSync(out, want);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  process.exit(main(process.argv.slice(2), root));
}
