#!/usr/bin/env node
// created: 2026-11-28 | branch: feat/v60-l0-wp09-flags
// author: Larry Klosowski (L0 lane, L0-WP09; Claude Opus 5.5)
// status: active
//
// Writes src/shell/flags.gen.ts from release/flags.json (one source, Rule 9), so the webview reads
// the same build-time flag values the Rust consts hold (src-tauri/src/flags_tests.rs ties the
// table to the consts). The table is the L0_INTEGRATION_SEAMS 3.7 shape:
//   { version: 1, flags: [{ id, lane: "L<N>", where, default, signoff: "required" | "none", record? }] }
// src/shell/flags.ts reads the generated module: flag(id: FlagId): boolean.
//
//   node scripts/gen-flags.mjs           # rewrite src/shell/flags.gen.ts
//   node scripts/gen-flags.mjs --check   # exit 1 if the committed file differs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const TABLE = "release/flags.json";
export const OUT = "src/shell/flags.gen.ts";

const IDENT = /^[A-Z][A-Z0-9_]*$/;
const LANE = /^L[0-9]$/;
const SIGNOFF = new Set(["required", "none"]);

// The fields the webview gets. `where` and `record` (repo paths) stay out of the bundle.
function row(r, i) {
  const at = `${TABLE} flags[${i}]`;
  if (!r || typeof r !== "object") throw new Error(`${at}: not an object`);
  if (typeof r.id !== "string" || !IDENT.test(r.id)) throw new Error(`${at}: id must be SCREAMING_CASE`);
  if (typeof r.default !== "boolean") throw new Error(`${at} ${r.id}: default must be true or false`);
  if (typeof r.lane !== "string" || !LANE.test(r.lane)) throw new Error(`${at} ${r.id}: lane must be L0..L9`);
  if (!SIGNOFF.has(r.signoff)) throw new Error(`${at} ${r.id}: signoff must be "required" or "none"`);
  return { id: r.id, lane: r.lane, default: r.default, signoff: r.signoff };
}

export function render(text) {
  const table = JSON.parse(text);
  if (table?.version !== 1) throw new Error(`${TABLE}: version must be 1`);
  if (!Array.isArray(table.flags)) throw new Error(`${TABLE}: missing flags array`);
  const rows = table.flags.map(row);
  const ids = new Set();
  for (const r of rows) {
    if (ids.has(r.id)) throw new Error(`${TABLE}: ${r.id} is listed twice`);
    ids.add(r.id);
  }
  const s = JSON.stringify;
  const lines = [
    "// created: 2026-11-28 | branch: feat/v60-l0-wp09-flags",
    "// author: Larry Klosowski (L0 lane, L0-WP09; generated by scripts/gen-flags.mjs)",
    "// status: active",
    "//",
    `// GENERATED by scripts/gen-flags.mjs from ${TABLE}. Do not edit; run \`node scripts/gen-flags.mjs\`.`,
    "// L0-WP09: the build-time feature flags. Read them with flag(id) from ./flags. A flag whose",
    '// signoff is "required" is true only with a verified record in release/signoffs/ (checked by',
    "// cargo test, src-tauri/src/flags_tests.rs).",
    "",
    "/** One build-time flag: its owning lane, its value in this build, and whether it needs a sign-off. */",
    "export interface FlagRow {",
    "  readonly id: string;",
    "  readonly lane: string;",
    "  readonly default: boolean;",
    '  readonly signoff: "required" | "none";',
    "}",
    "",
    "export const FLAG_ROWS: readonly FlagRow[] = [",
    ...rows.map((r) => `  { id: ${s(r.id)}, lane: ${s(r.lane)}, default: ${r.default}, signoff: ${s(r.signoff)} },`),
    "];",
    "",
    "/** Each flag's value in this build. */",
    "export const FLAGS = {",
    ...rows.map((r) => `  ${r.id}: ${r.default},`),
    "} as const;",
    "",
    "export type FlagId = keyof typeof FLAGS;",
    "",
  ];
  return lines.join("\n");
}

function main(argv, root) {
  const want = render(readFileSync(path.join(root, TABLE), "utf8"));
  const out = path.join(root, OUT);
  if (argv.includes("--check")) {
    let have = "";
    try {
      have = readFileSync(out, "utf8");
    } catch {
      have = "";
    }
    if (have !== want) {
      console.error(`${OUT} is stale; run node scripts/gen-flags.mjs`);
      return 1;
    }
    return 0;
  }
  writeFileSync(out, want);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  process.exit(main(process.argv.slice(2), root));
}
