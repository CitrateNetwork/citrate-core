// @vitest-environment node
//
// L0-WP10 dependency intake: every package a PR adds to Cargo.lock or package-lock.json must have a
// row in release/dep-intake.json (lane, reason, licence, reviewer, supply-chain result), a row must
// name packages the lockfiles actually hold, a federation git crate stays on one pinned rev and
// carries a [[drift]] entry, and a new `cargo audit --ignore` in ci.yml must carry an expiry.
// The root workspace takes lane crates from crates/* with no root edit.
// One defect per test, on in-memory lockfiles; the last tests run the real check on this repo.
import { afterEach, describe, expect, it } from "vitest";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cargoLockPackages, checkIntake, fedRepo, federationPins, npmLockPackages, sourceOrigin } from "./dep-intake.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const SCRIPT = path.join(here, "dep-intake.mjs");
const CHAIN = "git+https://github.com/CitrateNetwork/citrate-chain.git";
const REV = "68434069de707e8454a1313a1f2e20ba449300f5";

const tmpDirs = [];
afterEach(() => {
  for (const d of tmpDirs.splice(0)) fs.rmSync(d, { recursive: true, force: true });
});

/** A Cargo.lock with the given [name, source?] packages (no source = a workspace or path crate). */
function cargoLock(pkgs) {
  const body = pkgs
    .map(([name, source]) => `[[package]]\nname = "${name}"\nversion = "1.0.0"\n${source ? `source = "${source}"\n` : ""}`)
    .join("\n");
  return `# This file is automatically @generated by Cargo.\nversion = 4\n\n${body}`;
}

/** A package-lock.json (v3) with the given install paths (an [path, resolved, extra] entry sets the source and other fields). */
function npmLock(paths) {
  const packages = { "": { name: "citrate-core" } };
  for (const p of paths) {
    const [at, resolved, extra] = Array.isArray(p) ? p : [p, `https://registry.npmjs.org/${p.slice(p.lastIndexOf("node_modules/") + 13)}/-/x-1.0.0.tgz`];
    packages[at] = { version: "1.0.0", resolved, ...extra };
  }
  return JSON.stringify({ name: "citrate-core", lockfileVersion: 3, packages });
}

const REG = "registry+https://github.com/rust-lang/crates.io-index";
const baseCargo = cargoLock([["citrate-core"], ["serde", REG]]);
const baseNpm = npmLock(["node_modules/react"]);
const CI_OK = "      # RUSTSEC-2025-0055 grandfathered\n      cargo audit --ignore RUSTSEC-2025-0055\n";

function row(deps, extra = {}) {
  return {
    deps,
    lane: "L1",
    wp: "L1-WP02",
    reason: "ACP host client",
    licence: "Apache-2.0",
    reviewer: "L0 lead",
    supply_chain: { skill: "supply-chain-risk-auditor", result: "pass", notes: "maintained, single publisher" },
    origins: [REG],
    ...extra,
  };
}

function check({ rows = [], cargo = baseCargo, npm = baseNpm, base = baseCargo, ci = CI_OK, today = "2026-11-27", pins } = {}) {
  return checkIntake({
    intake: { version: 1, rows },
    base: { cargo: cargoLockPackages(base), npm: npmLockPackages(baseNpm) },
    head: { cargo: cargoLockPackages(cargo), npm: npmLockPackages(npm) },
    ciYml: ci,
    today,
    pins,
  });
}

describe("lockfile package sets", () => {
  it("reads third-party crates with their sources and skips workspace crates", () => {
    const pkgs = cargoLockPackages(cargoLock([["citrate-core"], ["serde", REG], ["citrate-wallet-core", `${CHAIN}?rev=${REV}#${REV}`]]));
    expect([...pkgs.keys()].sort()).toEqual(["cargo:citrate-wallet-core", "cargo:serde"]);
    expect([...pkgs.get("cargo:serde")]).toEqual([REG]);
  });

  it("reads npm package names from nested and scoped install paths", () => {
    const pkgs = npmLockPackages(npmLock(["node_modules/react", "node_modules/@tauri-apps/api", "node_modules/a/node_modules/@x/y"]));
    expect([...pkgs.keys()].sort()).toEqual(["npm:@tauri-apps/api", "npm:@x/y", "npm:react"]);
  });

  it("names an npm alias by its lock name and leaves out linked workspace packages", () => {
    const alias = ["node_modules/cbw-sdk", "https://registry.npmjs.org/@coinbase/wallet-sdk/-/wallet-sdk-4.0.0.tgz", { name: "@coinbase/wallet-sdk" }];
    const link = ["node_modules/citrate-ui", "packages/ui", { link: true }];
    expect([...npmLockPackages(npmLock([alias, link])).keys()]).toEqual(["npm:@coinbase/wallet-sdk"]);
    const out = ["node_modules/x", "../outside/x", { link: true }];
    expect([...npmLockPackages(npmLock([out])).get("npm:x")]).toEqual(["link:../outside/x"]);
  });

  it("reduces a source to its origin: no rev, commit or file", () => {
    expect(sourceOrigin(`${CHAIN}?rev=${REV}#${REV}`)).toBe(CHAIN);
    expect(sourceOrigin("https://registry.npmjs.org/react/-/react-19.1.0.tgz")).toBe("https://registry.npmjs.org/react");
    expect(sourceOrigin("https://registry.npmjs.org/@scope/a/-/a-1.0.0.tgz")).toBe("https://registry.npmjs.org/@scope/a");
    expect(sourceOrigin(REG)).toBe(REG);
  });

  it("finds a CitrateNetwork git source in every spelling cargo accepts", () => {
    for (const src of [
      `${CHAIN}?rev=${REV}#${REV}`,
      `git+https://github.com/CitrateNetwork/citrate-chain?rev=${REV}#${REV}`,
      `git+https://github.com/citratenetwork/Citrate-Chain.git?rev=${REV}#${REV}`,
      `git+http://github.com/CitrateNetwork/citrate-chain.git?rev=${REV}#${REV}`,
      "git+ssh://git@github.com/CitrateNetwork/citrate-chain.git?branch=main#abc",
      "git+ssh://git@github.com:22/CitrateNetwork/citrate-chain#abc",
      `git+https://www.github.com/CitrateNetwork/citrate-chain/?rev=${REV}#${REV}`,
    ]) {
      expect(fedRepo(src), src).toBe("citrate-chain");
    }
    expect(fedRepo("git+https://github.com/someone/citrate-chain.git#abc")).toBeNull();
    expect(fedRepo("git+https://github.com/CitrateNetwork-fork/citrate-chain.git#abc")).toBeNull();
    expect(fedRepo(REG)).toBeNull();
  });
});

describe("dep intake", () => {
  it("every_new_dep_has_an_intake_row", () => {
    const cargo = cargoLock([["citrate-core"], ["serde", REG], ["agent-client-protocol", REG]]);
    const npm = npmLock(["node_modules/react", "node_modules/left-pad"]);
    const errors = check({ cargo, npm });
    expect(errors).toEqual([
      expect.stringContaining("cargo:agent-client-protocol"),
      expect.stringContaining("npm:left-pad"),
    ]);
    expect(check({ cargo, npm, rows: [row(["cargo:agent-client-protocol", "npm:left-pad"], { origins: [REG, "https://registry.npmjs.org/left-pad"] })] })).toEqual([]);
  });

  it("an npm alias swap is a new package: the install path stays, the registry package changes", () => {
    const evil = ["node_modules/react", "https://registry.npmjs.org/evil-react/-/evil-react-1.0.0.tgz", { name: "evil-react" }];
    expect(check({ npm: npmLock([evil]) })).toEqual([expect.stringMatching(/npm:evil-react: new in this change and has no row/)]);
    // A hand-edited lock that drops the name still installs the resolved tarball, so the origin carries the package.
    const unnamed = ["node_modules/react", "https://registry.npmjs.org/evil-react/-/evil-react-1.0.0.tgz"];
    expect(check({ npm: npmLock([unnamed]) })).toEqual([expect.stringMatching(/npm:react: new in this change \(new source https:\/\/registry.npmjs.org\/evil-react\)/)]);
  });

  it("a reviewed package moved to a new source fails until its row lists that origin", () => {
    const acp = cargoLock([["citrate-core"], ["serde", REG], ["acp", REG]]);
    const reviewed = row(["cargo:acp"]);
    expect(check({ cargo: acp, base: acp, rows: [reviewed] })).toEqual([]);
    const FORK = "git+https://github.com/someone/acp.git";
    const forked = cargoLock([["citrate-core"], ["serde", REG], ["acp", `${FORK}#abc`]]);
    expect(check({ cargo: forked, base: acp, rows: [reviewed] })).toEqual([expect.stringMatching(new RegExp(`cargo:acp: source ${FORK.replace(/[.+]/g, "\\$&")} is not in .*origins`))]);
    expect(check({ cargo: forked, base: acp, rows: [row(["cargo:acp"], { origins: [FORK] })] })).toEqual([]);
  });

  it("a known name from a new source is new: a crates.io crate swapped for a git fork", () => {
    const fork = cargoLock([["citrate-core"], ["serde", REG], ["serde", "git+https://github.com/someone/serde.git#abc"]]);
    expect(check({ cargo: fork })).toEqual([expect.stringMatching(/cargo:serde: new in this change \(new source git\+https:\/\/github.com\/someone\/serde.git\)/)]);
    const npm = npmLock([["node_modules/react", "https://evil.example/react-19.1.0.tgz"]]);
    expect(check({ npm })).toEqual([expect.stringMatching(/npm:react: new in this change \(new source https:\/\/evil.example\/react-19.1.0.tgz\)/)]);
    const bump = cargoLock([["citrate-core"], ["serde", REG], ["serde", REG]]);
    expect(check({ cargo: bump })).toEqual([]);
  });

  it("intake_rows_without_a_dep_fail", () => {
    const errors = check({ rows: [row(["cargo:not-in-any-lockfile"])] });
    expect(errors).toEqual([expect.stringContaining("cargo:not-in-any-lockfile")]);
    expect(errors[0]).toMatch(/not in Cargo.lock or package-lock.json/);
  });

  it("a row missing a field, or with a failed supply-chain review, fails", () => {
    const cargo = cargoLock([["citrate-core"], ["serde", REG], ["acp", REG]]);
    expect(check({ cargo, rows: [row(["cargo:acp"], { reviewer: "" })] })).toEqual([expect.stringMatching(/reviewer/)]);
    expect(check({ cargo, rows: [row(["cargo:acp"], { lane: "L12" })] })).toEqual([expect.stringMatching(/lane/)]);
    const failed = { skill: "supply-chain-risk-auditor", result: "fail", notes: "abandoned" };
    expect(check({ cargo, rows: [row(["cargo:acp"], { supply_chain: failed })] })).toEqual([expect.stringMatching(/supply_chain/)]);
    expect(check({ cargo, rows: [row(["cargo:acp"]), row(["cargo:acp"])] })).toEqual([expect.stringMatching(/more than one row/)]);
  });

  it("a federation git crate needs a drift entry and stays on one pinned rev", () => {
    const fed = `${CHAIN}?rev=${REV}#${REV}`;
    const cargo = cargoLock([["citrate-core"], ["serde", REG], ["citrate-fork", fed]]);
    expect(check({ cargo, rows: [row(["cargo:citrate-fork"])] })).toEqual([expect.stringMatching(/\[\[drift\]\]/)]);
    expect(check({ cargo, rows: [row(["cargo:citrate-fork"], { drift: "citrate-core -> citrate-chain (citrate-fork)" })] })).toEqual([]);
    const other = "1111111111111111111111111111111111111111";
    const split = cargoLock([["citrate-core"], ["serde", REG], ["citrate-wallet-core", fed], ["citrate-commd", `${CHAIN}?rev=${other}#${other}`]]);
    expect(check({ cargo: split, base: split })).toEqual([expect.stringMatching(/citrate-chain.*one rev/)]);
    const branch = cargoLock([["citrate-core"], ["serde", REG], ["citrate-commd", `${CHAIN}?branch=main#${REV}`]]);
    expect(check({ cargo: branch, base: branch })).toEqual([expect.stringMatching(/citrate-commd.*rev/)]);
  });

  it("a federation crate in another spelling of the repo is still one repo on one pinned rev", () => {
    const other = "1111111111111111111111111111111111111111";
    const crate = (name, src) => cargoLock([["citrate-core"], ["serde", REG], ["citrate-wallet-core", `${CHAIN}?rev=${REV}#${REV}`], [name, src]]);
    const variants = {
      "no .git": `git+https://github.com/CitrateNetwork/citrate-chain?rev=${other}#${other}`,
      "lowercase org": `git+https://github.com/citratenetwork/citrate-chain.git?rev=${other}#${other}`,
      http: `git+http://github.com/CitrateNetwork/citrate-chain.git?rev=${other}#${other}`,
      ssh: `git+ssh://git@github.com/CitrateNetwork/citrate-chain.git?rev=${other}#${other}`,
    };
    for (const [what, src] of Object.entries(variants)) {
      const cargo = crate("citrate-commd", src);
      expect(check({ cargo, base: cargo }), what).toEqual([expect.stringMatching(/CitrateNetwork\/citrate-chain: federation crates must stay on one rev/)]);
    }
    const ssh = crate("citrate-commd", "git+ssh://git@github.com/CitrateNetwork/citrate-chain.git?branch=main#abc");
    expect(check({ cargo: ssh, base: ssh })).toEqual([expect.stringMatching(/citrate-commd: federation git source must pin a 40-hex rev=/)]);
    const fresh = crate("citrate-fork", `git+ssh://git@github.com/citratenetwork/citrate-chain?rev=${REV}#${REV}`);
    const before = cargoLock([["citrate-core"], ["serde", REG], ["citrate-wallet-core", `${CHAIN}?rev=${REV}#${REV}`]]);
    expect(check({ cargo: fresh, base: before, rows: [row(["cargo:citrate-fork"], { origins: ["git+ssh://git@github.com/citratenetwork/citrate-chain"] })] })).toEqual([
      expect.stringMatching(/cargo:citrate-fork: a federation crate needs drift/),
    ]);
  });

  it("federation crates sit on the federation pin that release/components.json records", () => {
    const other = "1111111111111111111111111111111111111111";
    const pins = federationPins({ components: [{ source: { repo: "CitrateNetwork/citrate-chain" }, federation: { rev: REV } }, { source: { repo: "ipfs/kubo" }, federation: { status: "not-pinned" } }] });
    expect([...pins]).toEqual([["citrate-chain", REV]]);
    const on = cargoLock([["citrate-core"], ["serde", REG], ["citrate-wallet-core", `${CHAIN}?rev=${REV}#${REV}`]]);
    expect(check({ cargo: on, base: on, pins })).toEqual([]);
    const moved = cargoLock([["citrate-core"], ["serde", REG], ["citrate-wallet-core", `${CHAIN}?rev=${other}#${other}`], ["citrate-commd", `${CHAIN}?rev=${other}#${other}`]]);
    expect(check({ cargo: moved, base: moved, pins })).toEqual([expect.stringMatching(new RegExp(`citrate-chain: crate rev ${other} is not the federation pin ${REV}`))]);
    // No component records the repo: the check proves one rev only (an accepted edge, in the script header).
    expect(check({ cargo: moved, base: moved })).toEqual([]);
  });

  it("a new cargo audit ignore needs an expiry that has not lapsed", () => {
    const add = (comment) => `${CI_OK}      # ${comment}\n      cargo audit --ignore RUSTSEC-2026-0999\n`;
    expect(check({ ci: add("RUSTSEC-2026-0999 reachable only in tests") })).toEqual([expect.stringMatching(/RUSTSEC-2026-0999.*EXPIRES/)]);
    expect(check({ ci: add("RUSTSEC-2026-0999 EXPIRES 2027-01-31") })).toEqual([]);
    // The date sits on the id's own line: an expiry elsewhere in the block does not carry over.
    const block = `${CI_OK}      # RUSTSEC-2026-0997 EXPIRES 2027-01-31\n      # RUSTSEC-2026-0999 reachable only in tests\n      cargo audit --ignore RUSTSEC-2026-0997 --ignore RUSTSEC-2026-0999\n`;
    expect(check({ ci: block })).toEqual([expect.stringMatching(/RUSTSEC-2026-0999.*EXPIRES/)]);
    expect(check({ ci: add("RUSTSEC-2026-0999 EXPIRES 2026-11-01") })).toEqual([expect.stringMatching(/lapsed/)]);
    const eq = `${CI_OK}      cargo audit --ignore=RUSTSEC-2026-0998\n`;
    expect(check({ ci: eq })).toEqual([expect.stringMatching(/RUSTSEC-2026-0998.*EXPIRES/)]);
  });
});

describe("this repo", () => {
  it("the committed intake and ci.yml pass against the current lockfiles", () => {
    const r = spawnSync(process.execPath, [SCRIPT, "check", "--repo", repoRoot], { encoding: "utf8" });
    expect(r.stderr).toBe("");
    expect(r.status).toBe(0);
    const bad = spawnSync(process.execPath, [SCRIPT, "check", "--repo", repoRoot, "--base", "--output=/dev/null"], { encoding: "utf8" });
    expect(bad.status).toBe(2);
    expect(bad.stderr).toMatch(/--base must be a git revision/);
  });

  it("ci.yml node job runs the intake check against the PR base", () => {
    const ci = fs.readFileSync(path.join(repoRoot, ".github", "workflows", "ci.yml"), "utf8");
    const node = ci.slice(ci.indexOf("\n  node:\n"));
    expect(node).toMatch(/node scripts\/dep-intake\.mjs check --base/);
  });

  it("the root workspace takes every crates/* directory, each a crate", () => {
    const toml = fs.readFileSync(path.join(repoRoot, "Cargo.toml"), "utf8");
    expect(toml).toMatch(/^members = \[[^\]]*"crates\/\*"[^\]]*\]$/m);
    const dir = path.join(repoRoot, "crates");
    expect(fs.existsSync(path.join(dir, "README.md"))).toBe(true);
    for (const d of fs.readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory())) {
      expect(fs.existsSync(path.join(dir, d.name, "Cargo.toml")), `crates/${d.name}`).toBe(true);
    }
  });

  // Runs cargo itself (on the CI runner and the build host, as every Rust job here does); metadata
  // with --no-deps --offline needs no network.
  it("cargo reads a synthetic crates/* workspace: a lane crate beside crates/README.md is a member", () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "wp10-ws-"));
    tmpDirs.push(root);
    const toml = fs.readFileSync(path.join(repoRoot, "Cargo.toml"), "utf8");
    const members = /^members = \[.*\]$/m.exec(toml)[0];
    fs.writeFileSync(path.join(root, "Cargo.toml"), `[workspace]\nresolver = "2"\nmembers = ["crates/*"]\n`);
    expect(members).toContain('"crates/*"');
    fs.mkdirSync(path.join(root, "crates", "lane-demo", "src"), { recursive: true });
    fs.copyFileSync(path.join(repoRoot, "crates", "README.md"), path.join(root, "crates", "README.md"));
    fs.writeFileSync(path.join(root, "crates", "lane-demo", "Cargo.toml"), '[package]\nname = "lane-demo"\nversion = "0.1.0"\nedition = "2021"\n');
    fs.writeFileSync(path.join(root, "crates", "lane-demo", "src", "lib.rs"), "pub fn f() {}\n");
    const r = spawnSync("cargo", ["metadata", "--no-deps", "--format-version", "1", "--offline"], { cwd: root, encoding: "utf8" });
    expect(r.stderr).not.toMatch(/error/);
    expect(JSON.parse(r.stdout).packages.map((p) => p.name)).toEqual(["lane-demo"]);
  });

  it("cargo reads this repo's root workspace with the crates/* glob", () => {
    const r = spawnSync("cargo", ["metadata", "--no-deps", "--format-version", "1", "--offline"], { cwd: repoRoot, encoding: "utf8", maxBuffer: 64 << 20 });
    expect(r.stderr).not.toMatch(/error/);
    expect(r.status).toBe(0);
    const names = JSON.parse(r.stdout).packages.map((p) => p.name);
    expect(names).toContain("citrate-core");
  });
});
